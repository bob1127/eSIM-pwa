export function getPartnerCountryPageMeta(countryKey, fallbackLabel) {
  const key = String(countryKey || "")
    .trim()
    .toLowerCase()
    .replace(/_/g, "-");
  const alias =
    key === "new-zealand" || key === "nz"
      ? "newzealand"
      : key === "fr"
        ? "france"
        : key === "tr" || key === "turkiye"
          ? "turkey"
          : key;
  const meta = PARTNER_COUNTRY_PAGE_META[alias] || PARTNER_COUNTRY_PAGE_META[key];
  if (meta) return meta;
  return {
    title: fallbackLabel ? `${fallbackLabel} eSIM` : "eSIM 方案",
    description: "精選高速 eSIM，QR Code 即開即用，免換實體卡。",
    tags: [
      { icon: "sim_card", label: "eSIM" },
      { icon: "qr_code_2", label: "即開即用" },
    ],
  };
}
