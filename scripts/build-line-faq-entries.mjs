/**
 * 從 line-oa/jeko_esim_line_ai_faq_utf8_bom.csv 產生 lib/lineFaqEntries.json
 * 用法：node scripts/build-line-faq-entries.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const CSV_PATH = path.join(ROOT, "line-oa/jeko_esim_line_ai_faq_utf8_bom.csv");
const OUT_PATH = path.join(ROOT, "lib/lineFaqEntries.js");

function parseCsvRecords(raw) {
  const records = [];
  let i = 0;
  const len = raw.length;
  while (i < len) {
    while (i < len && (raw[i] === "\n" || raw[i] === "\r")) i++;
    if (i >= len) break;
    const readField = () => {
      if (raw[i] === '"') {
        i++;
        let field = "";
        while (i < len) {
          if (raw[i] === '"') {
            if (raw[i + 1] === '"') {
              field += '"';
              i += 2;
            } else {
              i++;
              break;
            }
          } else {
            field += raw[i];
            i++;
          }
        }
        return field;
      }
      let field = "";
      while (i < len && raw[i] !== "," && raw[i] !== "\n" && raw[i] !== "\r") {
        field += raw[i];
        i++;
      }
      return field;
    };
    const a = readField();
    if (raw[i] === ",") i++;
    const b = readField();
    while (i < len && (raw[i] === "\n" || raw[i] === "\r")) i++;
    records.push([a, b]);
  }
  return records;
}

let text = fs.readFileSync(CSV_PATH, "utf8");
if (text.charCodeAt(0) === 0xfeff) text = text.slice(1);

const rows = parseCsvRecords(text);
const data = rows.slice(1).filter(([k, v]) => k && v);
const entries = data.map(([keywords, reply], idx) => ({
  id: idx + 1,
  keywords: keywords
    .split("/")
    .map((s) => s.trim())
    .filter(Boolean),
  reply: reply.trim().replace(/\r\n/g, "\n"),
}));

const body = `/** Auto-generated by scripts/build-line-faq-entries.mjs — do not edit by hand */\nexport default ${JSON.stringify(entries)};\n`;
fs.writeFileSync(OUT_PATH, body);
console.log(
  `Wrote ${entries.length} FAQ entries → ${path.relative(ROOT, OUT_PATH)}`,
);
const sample = entries.find((e) => e.reply.includes("🌼"));
console.log(
  sample
    ? `Tone check OK (🌼 found in id=${sample.id})`
    : "WARN: no 🌼 in replies",
);
