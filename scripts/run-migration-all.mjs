/**
 * 一鍵：建立 .env.migrate.local → 搬資料 → 更新 .env.local
 * 執行：node scripts/run-migration-all.mjs
 */
import { spawnSync } from "child_process";
import { readFileSync, writeFileSync, existsSync, copyFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const envLocal = resolve(root, ".env.local");
const migrateLocal = resolve(root, ".env.migrate.local");
const NEW_URL = "https://fxwwyqkowdmhofctrhjs.supabase.co";

function parseEnv(raw) {
  const o = {};
  for (const line of raw.split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq === -1) continue;
    let val = t.slice(eq + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    o[t.slice(0, eq).trim()] = val;
  }
  return o;
}

function loadEnv(path) {
  if (!existsSync(path)) return {};
  return parseEnv(readFileSync(path, "utf8"));
}

const env = loadEnv(envLocal);
const migrate = loadEnv(migrateLocal);

const oldUrl =
  migrate.OLD_SUPABASE_URL ||
  env.OLD_SUPABASE_URL ||
  env.NEXT_PUBLIC_SUPABASE_URL;
const oldKey =
  migrate.OLD_SUPABASE_SERVICE_ROLE_KEY ||
  env.OLD_SUPABASE_SERVICE_ROLE_KEY ||
  env.SUPABASE_SERVICE_ROLE_KEY;
let newUrl = migrate.NEW_SUPABASE_URL || env.NEW_SUPABASE_URL || NEW_URL;
let newKey =
  migrate.NEW_SUPABASE_SERVICE_ROLE_KEY ||
  env.NEW_SUPABASE_SERVICE_ROLE_KEY;

if (!oldUrl || !oldKey) {
  console.error("❌ 找不到舊專案 credentials（.env.local）");
  process.exit(1);
}

if (!newKey) {
  console.error(
    "❌ 缺少新專案 Service Role Key\n\n" +
      "請到 Supabase → Jeko-eSIM → Settings → API → service_role\n" +
      "複製後貼到 .env.migrate.local 的 NEW_SUPABASE_SERVICE_ROLE_KEY=\n" +
      "然後再執行：node scripts/run-migration-all.mjs",
  );
  process.exit(2);
}

if (newKey.startsWith("sb_publishable_") || newKey.startsWith("eyJ") && newKey.includes("anon")) {
  console.error(
    "❌ NEW_SUPABASE_SERVICE_ROLE_KEY 貼錯了！\n\n" +
      "你貼的是 anon / publishable key（sb_publishable_…）\n" +
      "請改貼 service_role secret（sb_secret_…）\n\n" +
      "Supabase → Jeko-eSIM → Settings → API\n" +
      "  · anon / publishable → NEW_SUPABASE_ANON_KEY\n" +
      "  · service_role secret → NEW_SUPABASE_SERVICE_ROLE_KEY",
  );
  process.exit(2);
}

// 寫入 / 更新 .env.migrate.local
writeFileSync(
  migrateLocal,
  `# auto-generated by run-migration-all.mjs\n` +
    `OLD_SUPABASE_URL=${oldUrl}\n` +
    `OLD_SUPABASE_SERVICE_ROLE_KEY=${oldKey}\n` +
    `NEW_SUPABASE_URL=${newUrl}\n` +
    `NEW_SUPABASE_SERVICE_ROLE_KEY=${newKey}\n`,
);

console.log("📦 開始搬移資料…");
const r = spawnSync("node", ["scripts/migrate-supabase-data.mjs"], {
  cwd: root,
  stdio: "inherit",
  env: { ...process.env },
});
if (r.status !== 0) process.exit(r.status || 1);

// 備份並更新 .env.local
const backup = resolve(root, `.env.local.backup-${Date.now()}`);
copyFileSync(envLocal, backup);
console.log(`\n💾 已備份 .env.local → ${backup.split("/").pop()}`);

let raw = readFileSync(envLocal, "utf8");
const newAnon =
  migrate.NEW_SUPABASE_ANON_KEY || env.NEW_SUPABASE_ANON_KEY || env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

function setLine(content, key, val) {
  const re = new RegExp(`^${key}=.*$`, "m");
  if (re.test(content)) return content.replace(re, `${key}=${val}`);
  return content.trimEnd() + `\n${key}=${val}\n`;
}

raw = setLine(raw, "NEXT_PUBLIC_SUPABASE_URL", newUrl);
raw = setLine(raw, "SUPABASE_SERVICE_ROLE_KEY", newKey);
if (migrate.NEW_SUPABASE_ANON_KEY || env.NEW_SUPABASE_ANON_KEY) {
  raw = setLine(
    raw,
    "NEXT_PUBLIC_SUPABASE_ANON_KEY",
    migrate.NEW_SUPABASE_ANON_KEY || env.NEW_SUPABASE_ANON_KEY,
  );
}

writeFileSync(envLocal, raw);
console.log("✅ .env.local 已切換到新專案 Jeko-eSIM");
console.log("\n若 anon key 也是新的，請確認 NEXT_PUBLIC_SUPABASE_ANON_KEY 已更新。");
console.log("完成後重啟：npm run dev");
