const AID = "125977";
const AFF_ADID = "1387309";

export function klookHotelAff(url) {
  const raw = String(url || "").trim();
  if (!raw) return raw;
  if (raw.startsWith("https://affiliate.klook.com/redirect")) return raw;
  let dest = raw;
  try {
    const parsed = new URL(raw);
    parsed.searchParams.delete("aid");
    parsed.searchParams.delete("spm");
    parsed.searchParams.delete("clickId");
    dest = parsed.toString();
  } catch {
    dest = raw;
  }
  return `https://affiliate.klook.com/redirect?aid=${AID}&aff_adid=${AFF_ADID}&k_site=${encodeURIComponent(dest)}`;
}

const KKDAY_CID = "25559";
function kkdayHotelAff(url) {
  const raw = String(url || "");
  if (!raw) return raw;
  if (/[?&]cid=/.test(raw)) return raw;
  const sep = raw.includes("?") ? "&" : "?";
  return `${raw}${sep}cid=${KKDAY_CID}`;
}

function hotelCategory(badge, starRating) {
  const b = String(badge || "");
  if (/溫泉/.test(b)) return "溫泉旅館";
  if (/親子|迪士尼|地標/.test(b)) return "主題飯店";
  if (/湖景|海景|溪流|富士山景|泳池/.test(b)) return "度假飯店";
  if (/祇園|客家|古鎮/.test(b)) return "精品旅館";
  return `${starRating} 星飯店`;
}

