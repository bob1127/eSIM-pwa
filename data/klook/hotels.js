function twdFromLabel(n) {
  return `TWD ${Number(n).toLocaleString("en-US")} 起`;
}

function hotel({
  hotelId,
  slug,
  tabId,
  regionLabel,
  title,
  subtitle,
  image,
  address,
  lat,
  lng,
  badge = "精選",
  starRating = 4,
  countryId = "japan",
}) {
  const priceFrom = HOTEL_PRICE_FROM_TWD[String(hotelId)] ?? HOTEL_PRICE_FROM_TWD[hotelId];
  return {
    id: `hotel-${hotelId}`,
    hotelId: String(hotelId),
    countryId,
    tabId,
    regionLabel,
    badge,
    title,
    subtitle,
    starRating,
    category: hotelCategory(badge, starRating),
    priceLabel: priceFrom ? twdFromLabel(priceFrom) : "TWD 入住報價 起",
    footer: "立即確認 · 免費取消視方案 · 價格依日期而異",
    url: klookHotelAff(
      `https://www.klook.com/zh-TW/hotels/detail/${hotelId}-${slug}/`,
    ),
    images: [image],
    description: `${title}，位於${regionLabel}。透過 Klook 聯盟連結預訂。`,
    features: [regionLabel, "Klook 聯盟專屬連結"],
    location: { name: title, address, lat, lng },
  };
}

